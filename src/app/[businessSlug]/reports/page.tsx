import { notFound } from "next/navigation";
import { BarChart3, TrendingUp, Sparkles, Repeat } from "lucide-react";
import { PageHeader } from "@/components/page-header";
import { TrendChart } from "@/components/trend-chart";
import { BreakdownBar } from "@/components/breakdown-bar";
import { StatTile, statMetaFor, EmptyState, Avatar } from "@/components/ui";
import { getReportsData } from "@/lib/reports-data";
import { requireTenantAccess } from "@/lib/auth";

export const dynamic = "force-dynamic";

type ReportsPageProps = { params: Promise<{ businessSlug: string }> };

export default async function ReportsPage({ params }: ReportsPageProps) {
  const { businessSlug } = await params;
  await requireTenantAccess(businessSlug);
  const data = await getReportsData(businessSlug);
  if (!data) notFound();

  return (
    <div className="grid gap-5">
      <PageHeader title="Reports" description="How the business is performing — revenue, bookings, services, and team.">
        <span className="inline-flex items-center gap-1.5 rounded-full border border-line bg-card px-3 py-1.5 text-[12.5px] font-semibold text-muted">
          <TrendingUp size={14} className="text-plum" /> {data.rangeLabel}
        </span>
      </PageHeader>

      <section className="grid grid-cols-4 gap-4 max-[1080px]:grid-cols-2 max-[640px]:grid-cols-1">
        {data.kpis.map((stat) => {
          const meta = statMetaFor(stat.label);
          return <StatTile key={stat.label} label={stat.label} value={stat.value} detail={stat.detail} icon={meta.icon} tone={meta.tone} />;
        })}
      </section>

      <section className="card p-5">
        <div className="mb-5 flex items-center gap-2">
          <span className="grid size-8 place-items-center rounded-xl bg-plum-soft text-plum"><BarChart3 size={16} /></span>
          <div>
            <h2 className="text-[15px] font-semibold">Revenue trend</h2>
            <p className="text-[12px] text-muted">Weekly takings over the last 6 weeks.</p>
          </div>
        </div>
        <TrendChart
          height={200}
          ariaLabel="Weekly revenue over the last 6 weeks"
          series={[
            {
              name: "Revenue",
              color: "var(--plum)",
              points: data.trend.map((bar) => ({ label: bar.label, value: bar.raw, display: bar.amount })),
            },
          ]}
        />
      </section>

      <section className="grid gap-5 lg:grid-cols-2">
        <div className="card p-5">
          <h2 className="flex items-center gap-2 text-[15px] font-semibold">
            <Sparkles size={17} className="text-plum" /> Top services
          </h2>
          <p className="mt-0.5 text-[12.5px] text-muted">By revenue over the last 30 days.</p>
          {data.topServices.length === 0 ? (
            <div className="mt-4"><EmptyState icon={Sparkles} title="No service revenue yet" body="Completed bookings will rank here." /></div>
          ) : (
            <div className="mt-4 grid gap-3.5">
              {data.topServices.map((svc, i) => (
                <div key={svc.name}>
                  <div className="mb-1.5 flex items-center justify-between gap-3 text-[13px]">
                    <span className="flex items-center gap-2 font-semibold text-ink">
                      <span className="grid size-5 place-items-center rounded-md bg-plum-soft text-[11px] font-bold text-plum">{i + 1}</span>
                      {svc.name}
                    </span>
                    <span className="font-semibold text-ink">{svc.revenue}</span>
                  </div>
                  <BreakdownBar share={svc.share} detail={`${svc.revenue} · ${svc.bookings} booking${svc.bookings === 1 ? "" : "s"}`} />
                  <div className="mt-1 text-[11.5px] text-muted">{svc.bookings} booking{svc.bookings === 1 ? "" : "s"}</div>
                </div>
              ))}
            </div>
          )}
        </div>

        <div className="card p-5">
          <h2 className="flex items-center gap-2 text-[15px] font-semibold">
            <BarChart3 size={17} className="text-plum" /> Team leaderboard
          </h2>
          <p className="mt-0.5 text-[12.5px] text-muted">Revenue generated by each team member (30 days).</p>
          {data.staff.length === 0 ? (
            <div className="mt-4"><EmptyState icon={BarChart3} title="No team revenue yet" body="Completed bookings by staff will rank here." /></div>
          ) : (
            <div className="mt-4 grid gap-4">
              {data.staff.map((person) => (
                <div key={person.name}>
                  <div className="flex items-center justify-between gap-3">
                    <div className="flex items-center gap-3">
                      <Avatar name={person.name} colorHex={person.colorHex} size={34} />
                      <div>
                        <div className="text-[13.5px] font-semibold text-ink">{person.name}</div>
                        <div className="text-[11.5px] text-muted">{person.bookings} booking{person.bookings === 1 ? "" : "s"}</div>
                      </div>
                    </div>
                    <div className="text-[13px] font-semibold text-ink">{person.revenue}</div>
                  </div>
                  <div className="mt-2">
                    <BreakdownBar share={person.util} detail={`${person.revenue} · ${person.bookings} booking${person.bookings === 1 ? "" : "s"}`} />
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </section>

      <section className="card p-5">
        <h2 className="flex items-center gap-2 text-[15px] font-semibold">
          <Repeat size={17} className="text-plum" /> Client retention
        </h2>
        <div className="mt-4 grid grid-cols-3 gap-4 max-[560px]:grid-cols-1">
          <div className="flex items-center gap-4 rounded-2xl border border-line-2 bg-plum-softer p-4">
            <div
              className="relative grid size-[72px] shrink-0 place-items-center rounded-full"
              style={{ background: `conic-gradient(var(--plum) ${data.retention.repeatRate * 3.6}deg, var(--sunken) 0deg)` }}
              role="img"
              aria-label={`Repeat rate ${data.retention.repeatRate} percent`}
            >
              <div className="grid size-[52px] place-items-center rounded-full bg-card text-[15px] font-semibold text-ink">
                {data.retention.repeatRate}%
              </div>
            </div>
            <div className="min-w-0">
              <div className="text-[13px] font-semibold text-ink">Repeat rate</div>
              <div className="text-[11.5px] text-muted">Last 60 days</div>
            </div>
          </div>
          <div className="rounded-2xl border border-line-2 p-4">
            <div className="text-[26px] font-semibold tracking-tight text-ink">{data.retention.returning}</div>
            <div className="mt-1 text-[12.5px] text-muted">Returning clients</div>
          </div>
          <div className="rounded-2xl border border-line-2 p-4">
            <div className="text-[26px] font-semibold tracking-tight text-ink">{data.retention.total}</div>
            <div className="mt-1 text-[12.5px] text-muted">Clients seen</div>
          </div>
        </div>
      </section>
    </div>
  );
}
